/** 全部 emoji，扁平数组。 */
export const EMOJI_CHOICES: string[] = EMOJI_GROUPS.flatMap((g) => g.items)

/**
 * 按关键字过滤 emoji 分组。
 *
 * emoji 本身没有可搜索的文本，这里只匹配**分组名**：
 * 输入「技术」返回技术组的全部 emoji，空关键字返回全部分组。
 */
export function searchEmojiGroups(query: string): EmojiGroup[] {
  const q = query.trim()
  if (!q) return EMOJI_GROUPS
  return EMOJI_GROUPS.filter((g) => g.label.includes(q))
}
