/** 品牌图标分组，顺序即面板里的展示顺序。 */
export const BRAND_GROUPS: BrandGroup[] = GROUPED.map(([label, items]) => ({
  label,
  items: items.map(([key, name, color, svg]) => ({ key, label: name, color, svg })),
}))

/** 全部品牌图标，扁平数组。 */
export const BRAND_ICONS: BrandIcon[] = BRAND_GROUPS.flatMap((g) => g.items)

/**
 * 取图标实际使用的颜色。
 *
 * 官方品牌色为纯黑或近黑的图标，深色主题下会看不见，统一换成 currentColor 跟随文字色。
 */
const DARK_BRAND_COLORS = new Set([
  '#000000', '#0f0f11', '#181717', '#231f20', '#2d3748', '#363636', '#003545',
])

export function brandColor(icon: BrandIcon): string {
  const raw = (icon.color ?? '').trim()
  if (!raw) return 'currentColor'
  if (DARK_BRAND_COLORS.has(raw.toLowerCase())) {
    return 'currentColor'
  }
  return raw
}

/**
 * 按关键字过滤品牌图标的分组。
 *
 * - 空关键字：返回全部分组；
 * - 命中分组名（如「语言」）：返回该组全部图标；
 * - 否则按图标 key / 显示名过滤，命中的图标归到它原本所在的分组。
 */
export function searchBrandGroups(query: string): BrandGroup[] {
  const q = query.trim().toLowerCase()
  if (!q) return BRAND_GROUPS

  const byGroupLabel = BRAND_GROUPS.filter((g) => g.label.toLowerCase().includes(q))
  if (byGroupLabel.length > 0) return byGroupLabel

  return BRAND_GROUPS.map((g) => ({
    label: g.label,
    items: g.items.filter(
      (it) => it.key.includes(q) || it.label.toLowerCase().includes(q),
    ),
  })).filter((g) => g.items.length > 0)
}

/** 按关键字过滤品牌图标，返回扁平数组（供「全部」页使用）。 */
export function searchBrandIcons(query: string): BrandIcon[] {
  return searchBrandGroups(query).flatMap((g) => g.items)
}
